"""
Тема: Работа со строками и пользовательский ввод.
Срезы, индексация, экранирование и базовые строковые методы.
"""

# 1. Индексация символов
author = "Чехов"
for char in author:
    print(char)

# 2. Сборка предложения из списка и удаление лишнего пробела
words = ["Рыжая", "лиса", "перепрыгнула", "через", "низкий", "забор", "."]
sentence = " ".join(words).replace(" .", ".")
print(sentence)

# 3. Замена символов и поиск индекса
quote = "Ребенок зеркало поступков родителей"
print(quote.replace("о", "0"))
print("Индекс буквы 'м' в слове Хемингуэй:", "Хемингуэй".index("м"))

# 4. Экранирование кавычек, перенос строки и умножение строк
print('Она сказала: "Непременно".\nА он ответил: "Конечно все получится!"')
print("три" * 3)

# 5. Срез и разделение строки
phrase = "И незачем так орать! Я и в первый раз прекрасно слышал."
print(phrase[0:19])

questions = "Где это? Кто это? Когда это?"
print(questions.split("?"))

# 6. Форматирование с пользовательским вводом
place_yesterday = input("Куда вы ходили вчера? ")
place_today = input("Куда вы ходили сегодня? ")
print(f"Вчера я ходил в {place_yesterday}, а сегодня я ходил в {place_today}.")
